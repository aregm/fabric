//! The fake's fixed RSA signing keys (2.2, 14.1).
//!
//! These are test keys that protect nothing. They were generated once with OpenSSL for this
//! crate, are public in the repository, and sign only the identity tokens of the fake. They are
//! written as numbers, not as a PEM file, so that no key file exists to be mistaken for a real
//! one. Never use them for anything else.
//!
//! Five keys: two ordinary ones (Google publishes two at a time), one with the public exponent
//! 3, one with a 1024-bit modulus, and one that no key set ever lists (the key of a `jwk`
//! header). The last three exist for the identity-token faults of 14.2.

use std::sync::OnceLock;

use base64::Engine;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use rsa::{BoxedUint, Pkcs1v15Sign, PrivateKey};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};

/// One of the fake's fixed signing keys.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum KeyId {
    /// The first ordinary key: 2048 bits, exponent 65537. It signs by default.
    A,
    /// The second ordinary key: 2048 bits, exponent 65537.
    B,
    /// A 2048-bit key with the public exponent 3 (refused by 3.5 item 3).
    WeakExponent,
    /// A key with a 1024-bit modulus (refused by 3.5 item 3).
    ShortModulus,
    /// A key that no key set lists by default; it signs the token of a `jwk` header fault.
    Attacker,
}

impl KeyId {
    /// Every key, in a fixed order.
    pub const ALL: [KeyId; 5] = [
        KeyId::A,
        KeyId::B,
        KeyId::WeakExponent,
        KeyId::ShortModulus,
        KeyId::Attacker,
    ];

    /// The key id (`kid`) the key set and the token header use for this key.
    pub fn kid(self) -> &'static str {
        match self {
            KeyId::A => "fake-key-a",
            KeyId::B => "fake-key-b",
            KeyId::WeakExponent => "fake-key-e3",
            KeyId::ShortModulus => "fake-key-short",
            KeyId::Attacker => "fake-key-attacker",
        }
    }

    /// The modulus, big-endian, without leading zeros.
    pub fn modulus(self) -> Vec<u8> {
        trim(components(self).0)
    }

    /// The public exponent.
    pub fn exponent(self) -> u32 {
        components(self).1
    }

    /// The key as a JSON Web Key, in the shape of Google's key set (`kty`, `alg`, `use`, `kid`,
    /// `n`, `e`).
    pub fn jwk(self) -> Value {
        let e = trim(&self.exponent().to_be_bytes());
        json!({
            "kty": "RSA",
            "alg": "RS256",
            "use": "sig",
            "kid": self.kid(),
            "n": URL_SAFE_NO_PAD.encode(self.modulus()),
            "e": URL_SAFE_NO_PAD.encode(e),
        })
    }
}

/// Signs `message` with RSASSA-PKCS1-v1_5 and SHA-256 (RS256) under the key `id`.
pub fn sign_rs256(id: KeyId, message: &[u8]) -> Vec<u8> {
    let digest = Sha256::digest(message);
    private_key(id)
        .sign(Pkcs1v15Sign::new::<Sha256>(), &digest)
        // The keys are fixed and the digest has the right length: this cannot fail.
        .expect("signing with a fixed test key")
}

/// The private key of `id`, built once per process.
fn private_key(id: KeyId) -> &'static PrivateKey {
    static KEYS: [OnceLock<PrivateKey>; 5] = [
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
        OnceLock::new(),
    ];
    let index = KeyId::ALL.iter().position(|k| *k == id).unwrap_or(0);
    KEYS[index].get_or_init(|| {
        let (n, e, d, p, q) = components(id);
        let bits = (n.len() * 8) as u32;
        let half = bits / 2;
        let big = |bytes: &[u8], precision: u32| {
            BoxedUint::from_be_slice(bytes, precision).expect("a fixed test key component")
        };
        PrivateKey::from_components(
            big(n, bits),
            BoxedUint::from(u64::from(e)),
            big(d, bits),
            vec![big(p, half), big(q, half)],
        )
        .expect("a fixed test key")
    })
}

type Components = (
    &'static [u8],
    u32,
    &'static [u8],
    &'static [u8],
    &'static [u8],
);

fn components(id: KeyId) -> Components {
    match id {
        KeyId::A => (&A_N, A_E, &A_D, &A_P, &A_Q),
        KeyId::B => (&B_N, B_E, &B_D, &B_P, &B_Q),
        KeyId::WeakExponent => (&E3_N, E3_E, &E3_D, &E3_P, &E3_Q),
        KeyId::ShortModulus => (&SHORT_N, SHORT_E, &SHORT_D, &SHORT_P, &SHORT_Q),
        KeyId::Attacker => (
            &ATTACKER_N,
            ATTACKER_E,
            &ATTACKER_D,
            &ATTACKER_P,
            &ATTACKER_Q,
        ),
    }
}

fn trim(bytes: &[u8]) -> Vec<u8> {
    let start = bytes.iter().position(|b| *b != 0).unwrap_or(bytes.len());
    bytes[start..].to_vec()
}

