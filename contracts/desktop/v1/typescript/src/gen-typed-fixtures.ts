// Writes .generated/typed-fixtures.ts: every accepted message fixture with a
// `value` source, as a literal that must satisfy its contract type. `tsc --noEmit`
// then checks that the TypeScript types accept what the schemas accept.
//   node src/gen-typed-fixtures.ts [contract dir]
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { canonical } from "./canonical.ts";
import { CONTRACT_ROOT, judge, loadContract } from "./judge.ts";
import { encodeText } from "./report.ts";

const OWNER = "owner-channel.schema.json#/$defs/";
const AGENT = "agent-channel.schema.json#/$defs/";
const COMMON = "common.schema.json#/$defs/";

export const ENTRY_TYPES: Readonly<Record<string, string>> = {
  [OWNER + "owner_request"]: "OwnerRequest",
  [OWNER + "owner_response"]: "OwnerResponse",
  [OWNER + "owner_notice"]: "OwnerNotice",
  [AGENT + "agent_request"]: "AgentRequest",
  [AGENT + "agent_response"]: "AgentResponse",
  [OWNER + "profile"]: "Profile",
  [OWNER + "grant"]: "Grant",
  [OWNER + "scope"]: "Scope",
  [OWNER + "enrollment"]: "Enrollment",
  [OWNER + "authorization"]: "Authorization",
  [OWNER + "recipient_set"]: "RecipientSet",
  [OWNER + "request"]: "Request",
  [OWNER + "proof_report"]: "ProofReport",
  [OWNER + "preferences"]: "Preferences",
  [COMMON + "limits"]: "Limits",
  [AGENT + "action"]: "Action",
  [AGENT + "request_status"]: "RequestStatus",
};

const root = process.argv[2] ?? CONTRACT_ROOT;
const contract = loadContract(root);
const dir = join(root, "fixtures", "messages");
const used = new Set<string>();
const lines: string[] = [];
readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .forEach((file, index) => {
    const e = JSON.parse(readFileSync(join(dir, file), "utf8"));
    if (!("value" in e)) return;
    if (judge(contract, e.schema, encodeText(canonical(e.value))).verdict !== "accept") return;
    const type = ENTRY_TYPES[e.schema];
    if (type === undefined) throw new Error(`${file}: no contract type for ${e.schema}`);
    used.add(type);
    lines.push(`// ${file}`, `export const f${index} = ${JSON.stringify(e.value)} as const satisfies ${type};`);
  });

const header = [
  "// Generated by src/gen-typed-fixtures.ts. Do not edit.",
  used.size > 0 ? `import type { ${[...used].sort().join(", ")} } from "../src/contract.ts";` : "export {};",
];
const out = fileURLToPath(new URL("../.generated/", import.meta.url));
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "typed-fixtures.ts"), [...header, ...lines, ""].join("\n"));
process.stdout.write(`wrote ${lines.length / 2} typed fixtures to .generated/typed-fixtures.ts\n`);
